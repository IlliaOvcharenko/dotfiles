    [ -n "${debian_chroot:-}" ] && chroot_name="($debian_chroot)"
    PS1='\[\e]0;\u@\h: \w\a\]'"$chroot_name"'\[\033[01;32m\]\u@\h\[\033[00m\]:\[\033[01;34m\]\w\[\033[00m\]\$ '
}

